"""evfeat-1 Python port (training/features.py) against the JS (app/src/events/features.js).

Golden files: tests/fixtures/evfeat-1.golden.json (owned by the events module: 45-frame 60 fps jittered input, both
handednesses) and training/tests/fixtures/evfeat-extra.json (generated by training/node/make_fixtures.mjs: dropped
frames, a 0.25 s gap, NaN rows, left-handed dtl, 1- and 2-frame sequences). Tolerance 1e-5 (CAFCR R2 / doc).
"""
import json
import shutil
import subprocess
from pathlib import Path

import numpy as np
import pytest

from features import FEATURE_NAMES, FEATURE_VERSION, compute_features, js_unwrap

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "tests" / "fixtures" / "evfeat-1.golden.json"
EXTRA = Path(__file__).resolve().parent / "fixtures" / "evfeat-extra.json"
TOL = 1e-5


def arr(x):
    return np.array([np.nan if v is None else v for v in x], dtype=np.float64)


def assert_close(got, want, what):
    both_nan = np.isnan(got) & np.isnan(want)
    assert np.array_equal(np.isnan(got), np.isnan(want)), f"{what}: NaN pattern differs"
    d = np.abs(np.where(both_nan, 0, got - want))
    assert d.max(initial=0) <= TOL, f"{what}: max |diff| {d.max()}"
    return float(d.max(initial=0))


def test_golden_evfeat1_both_handednesses():
    g = json.loads(GOLDEN.read_text())
    assert g["version"] == FEATURE_VERSION and tuple(g["names"]) == FEATURE_NAMES
    inp = g["input"]
    for hand in ("right", "left"):
        f = compute_features(inp["t_s"], np.asarray(inp["img"], np.float32), inp["W"], inp["H"], hand)
        want = np.asarray(g[f"features_{hand}"], dtype=np.float64)
        assert f["data"].shape == want.shape
        assert_close(f["t_s"], np.asarray(g["t_grid"]), "t_grid")
        assert_close(f["data"].ravel(), want.ravel(), f"features_{hand}")
    assert abs(compute_features(inp["t_s"], np.asarray(inp["img"], np.float32), inp["W"], inp["H"])["torso_px"]
               - g["torso_px"]) <= TOL


@pytest.mark.parametrize("case", json.loads(EXTRA.read_text())["cases"], ids=lambda c: c["name"])
def test_extra_cases(case):
    inp = case["input"]
    f = compute_features(arr(inp["t_s"]), arr(inp["img"]).astype(np.float32), inp["W"], inp["H"], case["handedness"])
    assert f["K"] == case["K"]
    assert_close(f["t_s"], arr(case["t_grid"]), "t_grid")
    assert abs(f["torso_px"] - case["torso_px"]) <= TOL
    assert_close(f["data"].ravel(), arr(case["data"]), case["name"])


def test_extra_fixture_is_current(tmp_path):
    """Regenerate the JS fixture with node and compare (skipped without node)."""
    node = shutil.which("node")
    if not node:
        pytest.skip("node not on PATH")
    r = subprocess.run([node, str(ROOT / "training" / "node" / "make_fixtures.mjs"), str(tmp_path)], cwd=ROOT,
                       capture_output=True, text=True, timeout=120)
    assert r.returncode == 0, r.stderr
    assert json.loads((tmp_path / "evfeat-extra.json").read_text()) == json.loads(EXTRA.read_text())
    assert json.loads((tmp_path / "decode-ordered.json").read_text()) == \
        json.loads((EXTRA.parent / "decode-ordered.json").read_text())


def test_unwrap_matches_numpy_without_nan():
    rng = np.random.default_rng(1)
    p = np.cumsum(rng.normal(0, 2.0, 500))
    p = np.arctan2(np.sin(p), np.cos(p))
    assert np.allclose(js_unwrap(p), np.unwrap(p), atol=1e-12)


def test_mirror_with_handedness_swap_is_identity():
    """Mirroring the frame (x -> 1 - x, L/R landmarks swapped, as a mirrored video would be labelled) and flipping
    the handedness gives the same canonical features: the mirror augmentation is a no-op for evfeat-1."""
    g = json.loads(GOLDEN.read_text())
    inp = g["input"]
    img = np.asarray(inp["img"], np.float32).reshape(-1, 33, 4)
    from features import LR_SWAP
    mir = img[:, list(LR_SWAP), :].copy()
    mir[:, :, 0] = 1 - mir[:, :, 0]
    a = compute_features(inp["t_s"], img, inp["W"], inp["H"], "right")["data"]
    b = compute_features(inp["t_s"], mir, inp["W"], inp["H"], "left")["data"]
    assert np.allclose(a, b, atol=1e-4)
