"""GolfDB keypoints -> PoseSeq-equivalent -> evfeat-1 features -> per-frame labels on the 30 Hz grid.

Data: training/cache/keypoints/<model>/<id>.npz (MediaPipe 1.2.2, see training/extract_keypoints.py), annotations
training/data/annotations/golfDB.pkl (generated by the vendored generate_splits.py; `split` 1..4).

PoseSeq: the npz `img` is already the PoseSeq layout (x_norm, y_norm, z, visibility per landmark, normalised to the
160x160 frame, which is what app/src/events/features.js expects together with W = H = 160). Undetected frames are
all-NaN in the cache; they are DROPPED from the PoseSeq (the app's pose worker emits no row when nothing is
detected; the 30 Hz resampling interpolates across the gap). t_s = the npz t_s (frame / video fps, 29.97).

Labels on the grid: event e (annotation events[1:-1][e], clip frame f_e = events[e+1] - events[0]) lands on the grid
index nearest to its time t_s_full[f_e] (clamped to the grid). All other indices are background (8).

Id 677 (split 3) is the only clip whose events are not non-decreasing: impact (168) > mid_follow_through (167).
Decision: keep it, and use the GolfDB evaluation definition for both training and evaluation. GolfDB's
correct_preds compares event i with the i-th *sorted* labelled frame (np.where(labels < 8)), i.e. impact = 167 and
mid_follow_through = 168; we train with the same sorted frames (`event_frames` sorts), so the training target is the
target eval.py scores against. A 1-frame swap; documented in docs/training.md.

Handedness: GolfDB has no handedness field (columns: id, youtube_id, player, sex, club, view, slow, events, bbox,
split). Left-handed clips are identified by player: the six left-handed tour players present in GolfDB
(LEFT_HANDED_PLAYERS, 37 clips). A pose check (wrist displacement address -> top along the image x axis, positive
for a mirrored swing) agrees on all 37 of them; see docs/training.md.
"""
from __future__ import annotations

import functools
import math
from pathlib import Path

import numpy as np

from features import FEATURE_HZ, compute_features, js_nearest_index

TRAINING = Path(__file__).resolve().parent
CACHE = TRAINING / "cache" / "keypoints"
ANNOT = TRAINING / "data" / "annotations" / "golfDB.pkl"

LEFT_HANDED_PLAYERS = frozenset({
    "BUBBA WATSON", "PHIL MICKELSON", "MIKE WEIR", "GREG CHALMERS", "TED POTTER JR", "TIM WILKINSON",
})
NONMONOTONIC_IDS = (677,)
VIEW_MAP = {"face-on": "face_on", "down-the-line": "dtl", "other": "dtl"}


@functools.lru_cache(maxsize=1)
def annotations():
    import pandas as pd  # noqa: local import, pandas is slow to import

    df = pd.read_pickle(ANNOT)
    rows = []
    for _, a in df.iterrows():
        rows.append({
            "id": int(a["id"]), "youtube_id": str(a["youtube_id"]), "player": str(a["player"]),
            "view": str(a["view"]), "slow": int(a["slow"]), "split": int(a["split"]),
            "events": np.asarray(a["events"], dtype=np.int64).copy(), "club": str(a["club"]),
        })
    rows.sort(key=lambda r: r["id"])
    return tuple(rows)


def annotation(clip_id: int) -> dict:
    a = annotations()[clip_id]
    assert a["id"] == clip_id
    return a


def handedness(a: dict) -> str:
    return "left" if a["player"].strip().upper() in LEFT_HANDED_PLAYERS else "right"  # one name has a trailing space


def event_frames(a: dict) -> np.ndarray:
    """8 clip-relative event frames (address..finish), sorted (GolfDB eval definition; only changes id 677)."""
    ev = a["events"] - a["events"][0]
    return np.sort(ev[1:-1])


def clip_frames(a: dict) -> int:
    ev = a["events"] - a["events"][0]
    return int(ev[-1]) + 1


@functools.lru_cache(maxsize=4096)
def load_clip(clip_id: int, model: str = "full"):
    with np.load(CACHE / model / f"{clip_id}.npz", allow_pickle=False) as z:
        return {
            "img": z["img"].astype(np.float32), "detected": z["detected"].astype(bool),
            "t_s": z["t_s"].astype(np.float64), "fps": float(z["fps"]), "W": int(z["W"]), "H": int(z["H"]),
        }


def pose_seq(clip: dict):
    """PoseSeq-equivalent (t_s, img (T',33,4) float32, W, H) with undetected frames dropped."""
    det = clip["detected"]
    return clip["t_s"][det], clip["img"][det], clip["W"], clip["H"]


def grid_labels(t_grid, t_events) -> np.ndarray:
    """Per-grid-index hard labels: nearest grid index of each event time; background elsewhere. Later events
    overwrite earlier ones on a collision (only possible with time compression); see soft labels in train_tcn."""
    K = len(t_grid)
    lab = np.full(K, 8, dtype=np.int64)
    for e, te in enumerate(t_events):
        lab[grid_index(t_grid, te)] = e
    return lab


def grid_index(t_grid, t: float) -> int:
    K = len(t_grid)
    k = int(round((t - t_grid[0]) * FEATURE_HZ))
    return min(K - 1, max(0, k))


def build_example(clip_id: int, model: str = "full", stretch: float = 1.0, noise: float = 0.0, rng=None,
                  drop: float = 0.0):
    """Features + labels for one clip. stretch scales time (>1 = slower swing); noise = std of additive noise on
    x_norm / y_norm (fraction of the frame); drop = probability of dropping a detected frame."""
    a = annotation(clip_id)
    clip = load_clip(clip_id, model)
    t_s, img, W, H = pose_seq(clip)
    if len(t_s) < 2:
        return None
    if noise > 0 or drop > 0:
        rng = rng or np.random.default_rng(0)
        if drop > 0:
            keep = rng.random(len(t_s)) >= drop
            keep[0] = keep[-1] = True
            t_s, img = t_s[keep], img[keep]
        if noise > 0:
            img = img.copy()
            img[:, :, :2] += rng.normal(0.0, noise, size=img[:, :, :2].shape).astype(np.float32)
    t_s = t_s * stretch
    f = compute_features(t_s, img, W, H, handedness(a))
    ef = event_frames(a)
    t_ev = clip["t_s"][ef] * stretch
    return {
        "id": clip_id, "x": f["data"].astype(np.float32), "t_grid": f["t_s"], "t_events": t_ev,
        "labels": grid_labels(f["t_s"], t_ev), "ev_idx": np.array([grid_index(f["t_s"], t) for t in t_ev]),
        "stretch": stretch,
    }


def grid_to_frames(t_grid, ks, clip_t_s, stretch: float = 1.0):
    """Map grid indices back to ORIGINAL clip frame indices (nearest frame time, like detect.js nearestIndex)."""
    return np.array([js_nearest_index(clip_t_s, float(t_grid[int(k)]) / stretch) for k in ks], dtype=np.int64)


def split_ids(split: int):
    """(train_ids, test_ids) for GolfDB split N: test = clips with split == N, train = the other 3 splits."""
    rows = annotations()
    test = [r["id"] for r in rows if r["split"] == split]
    train = [r["id"] for r in rows if r["split"] != split]
    return train, test


def carve_val(train_ids, frac: float = 0.12, seed: int = 20261104):
    """Validation subset of the training ids, grouped by youtube_id (no source video in both)."""
    rows = {r["id"]: r for r in annotations()}
    vids = sorted({rows[i]["youtube_id"] for i in train_ids})
    rng = np.random.default_rng(seed)
    rng.shuffle(vids)
    n_val = int(math.ceil(frac * len(vids)))
    val_v = set(vids[:n_val])
    val = [i for i in train_ids if rows[i]["youtube_id"] in val_v]
    tr = [i for i in train_ids if rows[i]["youtube_id"] not in val_v]
    return tr, val


def pose_hand_score(clip_id: int, model: str = "full") -> float:
    """Wrist x displacement address -> top in torso lengths (raw image, not canonicalised). Negative for a
    right-handed swing in face-on / dtl views; used only to cross-check LEFT_HANDED_PLAYERS."""
    a = annotation(clip_id)
    clip = load_clip(clip_id, model)
    ef = event_frames(a)
    img, det = clip["img"], clip["detected"]

    def near(f):
        for o in range(6):
            for g in (f - o, f + o):
                if 0 <= g < len(img) and det[g]:
                    return img[g]
        return None

    pa, pt = near(int(ef[0])), near(int(ef[3]))
    if pa is None or pt is None:
        return math.nan
    L = math.hypot(*(pa[[11, 12], :2].mean(0) - pa[[23, 24], :2].mean(0)))
    return float((pt[[15, 16], 0].mean() - pa[[15, 16], 0].mean()) / max(L, 1e-6))
