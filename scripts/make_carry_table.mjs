#!/usr/bin/env node
// scripts/make_carry_table.mjs — the quick-read carry table app/src/quick/carry-table.js (V04-SPEC §A.3; owner V4-B).
//
//   node scripts/make_carry_table.mjs            write the table
//   node scripts/make_carry_table.mjs --check    exit 1 when the file on disk is missing, was made for another
//                                                LM_PARAMS.version, or any cell differs from a fresh computation by more
//                                                than max(1.0 m, 1 %) (centre or σ)
//
// One row per club of session/settings.js CLUBS (driver 3w hybrid 5i 7i 9i pw sw) × ball speed 20, 22 … 80 m/s. Each
// cell is the carry of physics/lm/flight.js fly() with LM_PARAMS (the full-shot flight model, so the quick read and the
// refined shot use the same aerodynamics) over the club category's priors, which the live mode cannot measure:
// launch angle N(launch_v.mean, launch_v.sd) and spin loft N(spin_loft.mean, spin_loft.sd) → spin = A·v_club·sin(SL)/r
// (physics/lm/spin.js spinFromLoft, v_club = ball speed / smash prior mean). Mean and 1σ over a 3 × 3 Gauss–Hermite
// grid of the two priors (deterministic, 9 flights per cell), plus LM_PARAMS.flight.carry_model_sigma_frac in
// quadrature. Straight flights (no side spin): the quick read has no direction. All inputs are UNVERIFIED priors
// (physics/lm/params.js); the table only saves running RK4 on the phone at impact time (≤ 5 ms budget, §A.1).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fly } from '../app/src/physics/lm/flight.js';
import { LM_PARAMS } from '../app/src/physics/lm/params.js';
import { lmCategory, spinFromLoft } from '../app/src/physics/lm/spin.js';
import { CLUBS } from '../app/src/session/settings.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'app/src/quick/carry-table.js');
export const SPEED = Object.freeze({ min: 20, max: 80, step: 2 });
// 3-point Gauss–Hermite (probabilists'): nodes 0, ±√3 σ, weights 2/3, 1/6
const GH = [[-Math.sqrt(3), 1 / 6], [0, 2 / 3], [Math.sqrt(3), 1 / 6]];
const r1 = (x) => Math.round(x * 10) / 10;

/** Fresh table object (pure). */
export function buildTable() {
  const clubs = {};
  for (const [type] of CLUBS) {
    const cat = lmCategory(type);
    const P = LM_PARAMS.clubs[cat];
    const rows = [];
    for (let v = SPEED.min; v <= SPEED.max + 1e-9; v += SPEED.step) {
      let m1 = 0, m2 = 0;
      for (const [za, wa] of GH) {
        for (const [zs, ws] of GH) {
          const lv = P.launch_v.mean + za * P.launch_v.sd;
          const sl = P.spin_loft.mean + zs * P.spin_loft.sd;
          const spin = spinFromLoft(v / P.smash.mean, sl, type);
          const f = fly({ speed_mps: v, launch_v_deg: lv, spin_rpm: spin });
          const c = f.ok ? f.x : 0;
          m1 += wa * ws * c;
          m2 += wa * ws * c * c;
        }
      }
      const sd = Math.sqrt(Math.max(0, m2 - m1 * m1) + (LM_PARAMS.flight.carry_model_sigma_frac * m1) ** 2);
      rows.push([r1(m1), r1(sd)]);
    }
    clubs[type] = { category: cat, smash: P.smash.mean, smash_sd: P.smash.sd, launch_v_deg: P.launch_v.mean, rows };
  }
  return { version: LM_PARAMS.version, speed_mps: { ...SPEED }, clubs };
}

function render(T) {
  const lines = [
    '// quick/carry-table.js — GENERATED by scripts/make_carry_table.mjs (do not edit; `--check` verifies it). Lazy.',
    '// Carry centre and 1σ (m) per club × ball speed (m/s) over the club-category launch / spin-loft priors with the',
    '// physics/lm flight model (LM_PARAMS version below). rows[i] = [carry_m, sigma_m] at speed_mps.min + i·step.',
    // one club per line (diff-friendly)
    `export const CARRY_TABLE = Object.freeze({ version: ${JSON.stringify(T.version)}, speed_mps: ${JSON.stringify(T.speed_mps)}, clubs: Object.freeze({`,
  ];
  for (const [type, c] of Object.entries(T.clubs)) {
    lines.push(`  ${JSON.stringify(type)}: Object.freeze({ category: ${JSON.stringify(c.category)}, smash: ${c.smash}, smash_sd: ${c.smash_sd}, launch_v_deg: ${c.launch_v_deg}, rows: ${JSON.stringify(c.rows)} }),`);
  }
  lines.push('}) });', '');
  return lines.join('\n');
}

async function main() {
  const check = process.argv.includes('--check');
  const fresh = buildTable();
  if (!check) {
    fs.writeFileSync(OUT, render(fresh));
    console.log(`wrote ${path.relative(ROOT, OUT)} (${Object.keys(fresh.clubs).length} clubs × ${fresh.clubs.driver.rows.length} speeds, ${fresh.version})`);
    return;
  }
  if (!fs.existsSync(OUT)) { console.error('carry table missing: run node scripts/make_carry_table.mjs'); process.exit(1); }
  const { CARRY_TABLE: T } = await import(`${OUT}?t=${process.pid}`);
  const bad = [];
  if (T.version !== fresh.version) bad.push(`table made for ${T.version}, LM_PARAMS is ${fresh.version}: regenerate`);
  if (JSON.stringify(T.speed_mps) !== JSON.stringify(fresh.speed_mps)) bad.push('speed grid differs');
  let worst = 0;
  for (const [type, c] of Object.entries(fresh.clubs)) {
    const d = T.clubs?.[type];
    if (!d || d.rows.length !== c.rows.length) { bad.push(`${type}: missing or wrong length`); continue; }
    c.rows.forEach(([cm, cs], i) => {
      for (const [a, b, what] of [[cm, d.rows[i][0], 'carry'], [cs, d.rows[i][1], 'sigma']]) {
        const tol = Math.max(1.0, 0.01 * Math.abs(a));
        worst = Math.max(worst, Math.abs(a - b) / tol);
        if (!(Math.abs(a - b) <= tol)) bad.push(`${type} @ ${fresh.speed_mps.min + i * fresh.speed_mps.step} m/s ${what}: file ${b} vs ${a}`);
      }
    });
  }
  if (bad.length) { console.error(`carry table check FAILED:\n  ${bad.slice(0, 12).join('\n  ')}`); process.exit(1); }
  console.log(`carry table OK (${fresh.version}; worst |Δ| = ${worst.toFixed(2)} of the tolerance max(1.0 m, 1 %))`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
